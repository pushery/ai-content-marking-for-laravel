<?php

declare(strict_types=1);

return [

    /*
    |--------------------------------------------------------------------------
    | AI Content Marking for Laravel
    |--------------------------------------------------------------------------
    |
    | Configuration for the package. Published to config/ai-content-marking.php with
    | `php artisan vendor:publish --tag=ai-content-marking-config`.
    |
    | Read environment values with env() here and nowhere else. Outside a config
    | file env() returns null the moment the host app caches its config, so the
    | value silently collapses to its default in production and nowhere else.
    |
    */

    'notice' => [

        /*
        | The source types that get a notice from the `<x-ai-content-marking::notice>`
        | component, as codes of the IPTC Digital Source Type vocabulary. For a marking
        | of any other type the component renders nothing.
        |
        | The package ships words for these two in every locale it translates. A type
        | added here needs its words under `notice.<code>` in the published translations,
        | and the component refuses to render without them rather than show a key.
        */
        'source_types' => ['trainedAlgorithmicMedia', 'compositeWithTrainedAlgorithmicMedia'],

        /*
        | The element the notice appears in, one of p, span, small, div, figcaption and
        | aside. The component's `as` attribute picks another one for a single notice.
        */
        'element' => 'p',

    ],

    'reader' => [

        /*
        | The largest document, in bytes, that MarkingReader scans: 2 MiB by default.
        | A larger one is refused with a LengthException rather than read in part,
        | because a marking past the end of the part would read as no marking at all.
        |
        | Read typed, not cast, and held to a floor of one byte. `env()` hands back a
        | string, and `(int) 'abc'` is `0`, which would refuse every document. A value
        | that is no number, or one below the floor, keeps the default.
        */
        'max_bytes' => is_numeric($maxBytes = env('AI_CONTENT_MARKING_READER_MAX_BYTES')) && (int) $maxBytes >= 1
            ? (int) $maxBytes
            : 2_097_152,

    ],

    /*
    |--------------------------------------------------------------------------
    | Model register
    |--------------------------------------------------------------------------
    |
    | Whether each model the application uses watermarks the text it writes, keyed
    | by the name the application gives the model. `watermarks_text` is `yes`, `no`
    | or `unknown`, `source` says where that statement comes from, and `checked_on`
    | is the day it was last checked, as YYYY-MM-DD. The last two may be null:
    |
    |     'example-model' => [
    |         'watermarks_text' => 'unknown',
    |         'source' => 'https://example.com/model-card',
    |         'checked_on' => '2026-10-15',
    |     ],
    |
    | The package ships no entries, because whether a model watermarks text is for
    | its provider to state and for the application to check. A model that is not
    | listed reads as `unknown`, and the gap report names it as not in the register.
    |
    */

    'models' => [],

    'gaps' => [

        /*
        | The length, in the model's tokens, from which the gap report expects a
        | watermark in an output. Shorter text is "very short text" in the European
        | Commission's Code of Practice on the transparency of content generated by
        | AI, which draws the line at 200 tokens and expects it to fall as
        | watermarking improves.
        |
        | Read typed, not cast, and held to a floor of one token. A value that is no
        | number, or one below the floor, keeps the default.
        */
        'watermark_from_tokens' => is_numeric($watermarkFromTokens = env('AI_CONTENT_MARKING_WATERMARK_FROM_TOKENS')) && (int) $watermarkFromTokens >= 1
            ? (int) $watermarkFromTokens
            : 200,

    ],

];
